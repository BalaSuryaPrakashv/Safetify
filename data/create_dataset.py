def create_dataset():
    danger_data = [{"text": phrase, "label": 1} for phrase in DANGER_PHRASES]
    normal_data = [{"text": phrase, "label": 0} for phrase in NORMAL_PHRASES]

    df = pd.DataFrame(danger_data + normal_data)
    df = df.sample(frac=1, random_state=42).reset_index(drop=True)

    os.makedirs("data", exist_ok=True)
    df.to_csv("data/dataset.csv", index=False)

    danger_count = df[df["label"] == 1].shape[0]
    normal_count = df[df["label"] == 0].shape[0]

    print(f"Dataset created: {len(df)} total samples")
    print(f"  DANGER : {danger_count}")
    print(f"  NORMAL : {normal_count}")
    print(f"  Ratio  : {danger_count/normal_count:.2f}  (ideal = 1.00)")
    print("Saved to data/dataset.csv")


if __name__ == "__main__":
    create_dataset()
